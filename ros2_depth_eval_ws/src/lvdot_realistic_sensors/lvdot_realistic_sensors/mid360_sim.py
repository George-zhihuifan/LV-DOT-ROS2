"""
Livox Mid-360 Simulation Node — emulates the Mid-360's non-repetitive
Risley-prism scan pattern on top of Gazebo's regular-grid gpu_lidar output.

Real Mid-360 characteristics modelled here:
  - 360° horizontal × 59° vertical FOV (−7° to +52°)
  - Non-repetitive "rose curve" scan trajectory generated by two counter-
    rotating Risley prisms.  Trajectory advances per frame so coverage is
    non-repeating within a few seconds (real Mid-360: 100% scene coverage
    after ~0.1 s at 10 Hz).
  - ~20,000 points per frame @ 10 Hz (= 200K pts/sec).
  - Range 0.1–70 m
  - Range noise σ ≈ 2 cm @ 25 m

This node subscribes to /uav_lidar/scan/points (dense regular-grid from
Gazebo's gpu_lidar), resamples points along the Mid-360 trajectory for the
current frame, and republishes on /livox/lidar/pointcloud with the
Mid-360-style point distribution.

The trajectory generator uses the well-known dual-Risley parametric
equations (see Marshall, "Risley prism scanners for ladar applications",
SPIE 2016).  Two prisms with deviation angle ψ rotate at speeds ω_1, ω_2
producing instantaneous beam direction:

    θ(t) = arctan2( sin(ω_1 t) − γ sin(ω_2 t),
                    cos(ω_1 t) + γ cos(ω_2 t) )
    φ(t) = sqrt( … )  → bounded by the Mid-360 vertical FOV envelope

We sample N=20,000 trajectory points per frame, advancing the phase
between frames so no two frames cover identical points (the "non-
repetitive" property).
"""

import struct
import array
import numpy as np
import rclpy
from rclpy.node import Node
from rclpy.qos import qos_profile_sensor_data
from sensor_msgs.msg import PointCloud2, PointField
from std_msgs.msg import Header


# Mid-360 spec parameters
MID360_HFOV_DEG = 360.0
MID360_VFOV_MIN_DEG = -7.0
MID360_VFOV_MAX_DEG = 52.0
MID360_RANGE_MIN_M = 0.1
MID360_RANGE_MAX_M = 70.0
MID360_RATE_HZ = 10.0
MID360_POINTS_PER_FRAME = 20000
MID360_RANGE_NOISE_PER_M = 0.0008  # σ ≈ 2cm @ 25m → 0.0008 per meter


class Mid360Trajectory:
    """Risley-prism non-repetitive trajectory generator."""

    def __init__(self, points_per_frame: int = MID360_POINTS_PER_FRAME,
                 rate_hz: float = MID360_RATE_HZ) -> None:
        self.points_per_frame = points_per_frame
        self.rate_hz = rate_hz
        # Two prism angular speeds (rad/s).  Real Mid-360 uses ω_1 ~ 5400, ω_2 ~ 4750.
        # Their ratio is irrational → non-repetitive.
        self._omega1 = 5400.0
        self._omega2 = 4750.0 * (1.0 + 1.0 / np.pi)  # irrational ratio
        # Deviation angle of one prism (rad).  Real Mid-360 ψ ≈ 30°.
        self._psi = np.deg2rad(30.0)
        # Phase accumulator across frames — this is what makes the scan
        # non-repetitive across frame boundaries.
        self._phase = 0.0
        # Vertical envelope (linear interpolation, not exact Risley math, but
        # gives the right coverage range).
        self._vmin = np.deg2rad(MID360_VFOV_MIN_DEG)
        self._vmax = np.deg2rad(MID360_VFOV_MAX_DEG)

    def next_frame(self) -> tuple:
        """Returns (azimuth_rad, elevation_rad) for one frame of points."""
        n = self.points_per_frame
        dt = 1.0 / self.rate_hz
        # Time samples within this frame
        t_local = np.linspace(0.0, dt, n, endpoint=False)
        # Add accumulated phase from prior frames
        t_global = self._phase + t_local
        self._phase += dt

        # Dual-Risley parametric equations
        a1 = self._omega1 * t_global
        a2 = self._omega2 * t_global
        # Beam direction tilts in x,y by combined prism deflections
        bx = self._psi * (np.cos(a1) + np.cos(a2))
        by = self._psi * (np.sin(a1) + np.sin(a2))
        # azimuth = atan2(by, bx)  — sweeps full 360°
        azim = np.arctan2(by, bx)
        # elevation modulated by radial distance + slow drift for full
        # vertical coverage
        r = np.sqrt(bx * bx + by * by)
        # Normalize r into [0, 1] using its theoretical maximum 2ψ
        r_norm = np.clip(r / (2.0 * self._psi), 0.0, 1.0)
        # Map to [vmin, vmax] with a slow modulation per frame so vertical
        # coverage spreads across frames
        drift = 0.5 + 0.5 * np.sin(2.0 * np.pi * self._phase * 0.3)
        elev = self._vmin + (self._vmax - self._vmin) * (
            0.5 * (1.0 - np.cos(np.pi * r_norm)) * drift +
            0.5 * (1.0 - np.cos(np.pi * (1.0 - r_norm))) * (1.0 - drift)
        )
        return azim, elev


def encode_pointcloud2(points_xyz: np.ndarray, intensity: np.ndarray,
                      frame_id: str, stamp) -> PointCloud2:
    """Build a sensor_msgs/PointCloud2 with x,y,z,intensity fields."""
    n = points_xyz.shape[0]
    fields = [
        PointField(name='x', offset=0, datatype=PointField.FLOAT32, count=1),
        PointField(name='y', offset=4, datatype=PointField.FLOAT32, count=1),
        PointField(name='z', offset=8, datatype=PointField.FLOAT32, count=1),
        PointField(name='intensity', offset=12, datatype=PointField.FLOAT32, count=1),
    ]
    point_step = 16
    data = np.empty((n, 4), dtype=np.float32)
    data[:, 0:3] = points_xyz.astype(np.float32)
    data[:, 3] = intensity.astype(np.float32)
    msg = PointCloud2()
    msg.header = Header()
    msg.header.stamp = stamp
    msg.header.frame_id = frame_id
    msg.height = 1
    msg.width = n
    msg.fields = fields
    msg.is_bigendian = False
    msg.point_step = point_step
    msg.row_step = point_step * n
    msg.is_dense = True
    # rclpy validates bytes element-by-element (~200 ms/MB); array.array('B', ...) bypasses that.
    msg.data = array.array('B', data.tobytes())
    return msg


def decode_xyz_from_pointcloud2(cloud: PointCloud2) -> np.ndarray:
    """Quick decode of x,y,z (assumes float32 fields packed at the front)."""
    arr = np.frombuffer(cloud.data, dtype=np.uint8).reshape(
        cloud.width * cloud.height, cloud.point_step)
    # Try to find x,y,z field offsets
    name_to_off = {f.name: f.offset for f in cloud.fields}
    xo = name_to_off.get('x', 0)
    yo = name_to_off.get('y', 4)
    zo = name_to_off.get('z', 8)
    x = np.frombuffer(arr[:, xo:xo+4].tobytes(), dtype=np.float32)
    y = np.frombuffer(arr[:, yo:yo+4].tobytes(), dtype=np.float32)
    z = np.frombuffer(arr[:, zo:zo+4].tobytes(), dtype=np.float32)
    return np.stack([x, y, z], axis=-1)


class Mid360Sim(Node):
    def __init__(self) -> None:
        super().__init__("mid360_sim")

        self.declare_parameter("input_topic", "/uav_lidar/scan/points")
        self.declare_parameter("output_topic", "/mid360/pointcloud")
        self.declare_parameter("frame_id", "livox_frame")
        self.declare_parameter("points_per_frame", MID360_POINTS_PER_FRAME)
        self.declare_parameter("range_noise_per_m", MID360_RANGE_NOISE_PER_M)

        in_topic = self.get_parameter("input_topic").value
        out_topic = self.get_parameter("output_topic").value

        self.pub = self.create_publisher(PointCloud2, out_topic, qos_profile_sensor_data)
        self.create_subscription(PointCloud2, in_topic, self.on_cloud, qos_profile_sensor_data)

        self._rng = np.random.default_rng(seed=7)

        self.get_logger().info(
            f"Mid-360 sim: {in_topic}→{out_topic}, target ≤{int(self.get_parameter('points_per_frame').value)} pts/frame, "
            f"FOV 360°×{MID360_VFOV_MAX_DEG - MID360_VFOV_MIN_DEG}°, range {MID360_RANGE_MIN_M}-{MID360_RANGE_MAX_M}m, "
            f"range noise σ≈{MID360_RANGE_NOISE_PER_M*100:.3f}% of r"
        )

    def on_cloud(self, cloud: PointCloud2) -> None:
        # Decode dense input cloud and keep finite points (Gazebo emits Inf for no-return rays).
        pts = decode_xyz_from_pointcloud2(cloud)
        valid = (
            np.isfinite(pts).all(axis=1)
            & (np.abs(pts).max(axis=1) < 1e4)
            & (np.linalg.norm(pts, axis=1) > MID360_RANGE_MIN_M)
        )
        pts = pts[valid]
        if pts.shape[0] == 0:
            return

        # Mid-360 vertical FOV cull: keep only rays inside [-7°, +52°] elevation.
        # (Gazebo gpu_lidar is already configured to roughly match, but be defensive.)
        rng_in = np.linalg.norm(pts, axis=1)
        elev_in = np.arcsin(np.clip(pts[:, 2] / np.maximum(rng_in, 1e-6), -1.0, 1.0))
        in_fov = (
            (elev_in >= np.deg2rad(MID360_VFOV_MIN_DEG))
            & (elev_in <= np.deg2rad(MID360_VFOV_MAX_DEG))
        )
        pts = pts[in_fov]
        rng_in = rng_in[in_fov]
        if pts.shape[0] == 0:
            return

        # The original implementation tried to project a synthetic Risley trajectory onto the
        # input cloud via a 1024×128 bin lookup. Because the Gazebo lidar is sparse (≤14% finite),
        # ~99% of trajectory bins miss and the output collapses to a handful of points.
        # We instead treat the Gazebo rays as the *real* ray hits (which is exactly what Mid-360
        # would also see), apply Mid-360 range noise per spec, and optionally subsample to the
        # configured points_per_frame target so the detector sees a realistic Mid-360 density.

        noise_per_m = float(self.get_parameter("range_noise_per_m").value)
        target = int(self.get_parameter("points_per_frame").value)

        n_in = pts.shape[0]
        if 0 < target < n_in:
            idx = self._rng.choice(n_in, size=target, replace=False)
            pts = pts[idx]
            rng_in = rng_in[idx]

        # Vectorized range noise: σ(r) = noise_per_m × r, no Python loop, no dict lookup.
        noise = self._rng.normal(0.0, noise_per_m * rng_in).astype(np.float32)
        rng_out = np.clip(rng_in + noise, MID360_RANGE_MIN_M, MID360_RANGE_MAX_M).astype(np.float32)
        scale = (rng_out / np.maximum(rng_in, 1e-6)).astype(np.float32)
        pts_out = pts.astype(np.float32) * scale[:, None]
        intensity_out = np.minimum(255.0, 5000.0 / (rng_out * rng_out + 0.1)).astype(np.float32)

        msg = encode_pointcloud2(
            pts_out, intensity_out,
            frame_id=self.get_parameter("frame_id").value,
            stamp=cloud.header.stamp,
        )
        self.pub.publish(msg)


def main() -> None:
    rclpy.init()
    node = Mid360Sim()
    rclpy.spin(node)
    node.destroy_node()
    rclpy.shutdown()


if __name__ == "__main__":
    main()
